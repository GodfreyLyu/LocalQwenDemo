"""Resolve one project's locks, installing the local contract separately from PyPI deps."""

import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", choices=("backend", "inference-service"), required=True)
    args = parser.parse_args()
    directory = ROOT / args.project
    with tempfile.TemporaryDirectory(prefix="llm-lock-") as temporary:
        override = Path(temporary) / "contract.txt"
        override.write_text("local-llm-contract @ " + (ROOT / "contracts").as_uri() + "\n")
        for extra, filename in (
            ([], "requirements.lock"),
            (["--extra", "dev"], "requirements-dev.lock"),
        ):
            destination = directory / filename
            command = [
                "uv",
                "pip",
                "compile",
                str(directory / "pyproject.toml"),
                "--python",
                sys.executable,
                "--override",
                str(override),
                "--no-emit-package",
                "local-llm-contract",
                "--no-header",
                "--no-annotate",
                "--quiet",
                "-o",
                str(destination),
                *extra,
            ]
            if extra:
                command += ["--constraint", str(directory / "requirements.lock")]
            subprocess.run(command, cwd=ROOT, check=True)
            destination.write_text(
                f"# Generated by python scripts/lock_dependencies.py --project {args.project}\n"
                "# Install the local contracts package separately with --no-deps.\n"
                + destination.read_text()
            )


if __name__ == "__main__":
    main()
